//! Minimal networking so pacman and apt work: loopback up, then dhcpcd in
//! the background on every interface (if installed). Never fatal.
//!
//! `wait_online()` then gives DHCP a few seconds before the shells appear:
//! a command typed right at the prompt (`apt update`) used to run before
//! eth0 had an address or /etc/resolv.conf a nameserver, so every download
//! failed once ("Ign:") and apt 2.7 flooded the console with
//! "W: Tried to start delayed item ..., but failed".

use std::fs;
use std::path::Path;
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

/// Longest we hold the consoles back waiting for DHCP. Plan B: after this
/// the shells start anyway and dhcpcd keeps trying in the background.
const WAIT_ONLINE: Duration = Duration::from_secs(15);

pub fn start() {
    let quiet = |c: &mut Command| c.stdout(Stdio::null()).stderr(Stdio::null()).status();
    match quiet(Command::new("/usr/bin/ip").args(["link", "set", "lo", "up"])) {
        Ok(s) if s.success() => {}
        other => crate::warn(&format!("loopback: ip link set lo up: {other:?}")),
    }
    if !Path::new("/usr/bin/dhcpcd").exists() {
        crate::warn("dhcpcd not installed (cargo am rootfs --update): no network");
        return;
    }
    // -b: fork to background right away; -q: quiet on the console;
    // --nodev: don't wait for udev to "initialise" interfaces. Keep this
    // fallback even with udev supervision: device discovery is allowed to
    // fail or be disabled without losing DHCP and the console.
    match quiet(Command::new("/usr/bin/dhcpcd").args(["-b", "-q", "--nodev"])) {
        Ok(s) if s.success() => crate::log("dhcpcd started"),
        other => crate::warn(&format!("dhcpcd: {other:?}")),
    }
}

/// True if any interface other than `lo` exists (no NIC -> nothing to wait for).
fn has_nic() -> bool {
    fs::read_dir("/sys/class/net")
        .map(|d| d.flatten().any(|e| e.file_name() != "lo"))
        .unwrap_or(false)
}

/// A default route in /proc/net/route (destination 00000000).
fn has_default_route(route_table: &str) -> bool {
    route_table
        .lines()
        .skip(1)
        .any(|l| l.split_whitespace().nth(1) == Some("00000000"))
}

/// resolv.conf names at least one nameserver.
fn has_nameserver(resolv: &str) -> bool {
    resolv
        .lines()
        .any(|l| l.split_whitespace().next() == Some("nameserver"))
}

/// Wait (bounded) until there is a default route and a nameserver.
/// `aftermath.netwait=0` on the kernel command line skips it; never fatal.
pub fn wait_online() {
    if !Path::new("/usr/bin/dhcpcd").exists() || !has_nic() {
        return;
    }
    let limit = match fs::read_to_string("/proc/cmdline") {
        Ok(c) => c
            .split_whitespace()
            .find_map(|w| w.strip_prefix("aftermath.netwait="))
            .and_then(|v| v.parse().ok())
            .map(Duration::from_secs)
            .unwrap_or(WAIT_ONLINE),
        Err(_) => WAIT_ONLINE,
    };
    if limit.is_zero() {
        return;
    }
    let start = Instant::now();
    loop {
        let route = fs::read_to_string("/proc/net/route").unwrap_or_default();
        let resolv = fs::read_to_string("/etc/resolv.conf").unwrap_or_default();
        if has_default_route(&route) && has_nameserver(&resolv) {
            crate::log(&format!(
                "network up after {:.1}s",
                start.elapsed().as_secs_f32()
            ));
            return;
        }
        if start.elapsed() >= limit {
            crate::warn(&format!(
                "no network after {}s - starting shells anyway (dhcpcd keeps trying)",
                limit.as_secs()
            ));
            return;
        }
        std::thread::sleep(Duration::from_millis(200));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_route() {
        let t = "Iface\tDestination\tGateway \tFlags\nlo\t0000007F\t00000000\t0001\n";
        assert!(!has_default_route(t));
        let t = format!("{t}eth0\t00000000\t0202000A\t0003\n");
        assert!(has_default_route(&t));
    }

    #[test]
    fn nameserver() {
        assert!(!has_nameserver("# Generated by dhcpcd\nsearch x\n"));
        assert!(has_nameserver(
            "# Generated by dhcpcd\nnameserver 10.0.2.3\n"
        ));
    }
}
